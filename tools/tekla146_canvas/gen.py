#!/usr/bin/env python3
"""Tekla 146 dialog -> model-maker "canvas" tabs generator.

Inputs
  maps/map_<Tab>.json   control map per Tekla tab screenshot (pixel boxes in the
                        ORIGINAL screenshot, control kind, parameter name, greyed)
  <shots>/<Tab>.png     the user's real Tekla "Shear plate simple (146)" tab screenshots

Outputs (repo-relative)
  resources/tekla146/tabs/<slug>.png      tab panel crop = canvas background
  src/component_dialog_146_canvas.cpp     applyShearPlate146Canvas() tables

usage: python3 gen.py <screenshot_dir> [<repo_root>]
Needs Pillow + numpy. Re-run after editing a map; never edit the .cpp by hand.
"""
import json
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))

# screenshot stem -> dialog tab title (component_dialog.cpp group titles)
TITLES = {
    "Picture": "Picture", "Plates": "Plates", "Stiffners": "Stiffeners",
    "General": "General", "Haunch": "Haunch", "Notch": "Notch", "Bolts": "Bolts",
    "Design Type": "Design type", "Beam Cut": "Beam cut", "Angle Box": "Angle box",
    "BoxPBolts": "BoxPBolts", "BoxSBolts": "BoxSBolts", "Analysis": "Analysis",
}
ORDER = list(TITLES)

KIND = {"edit": "Edit", "combo": "Combo", "iconcombo": "IconCombo",
        "check": "Check", "defaultcheck": "DefaultCheck"}


def panel_bounds(img):
    """Tab panel = between the two long horizontal frame lines below the tab strip."""
    g = np.asarray(img.convert("L")).astype(int)
    H, W = g.shape
    rows = [y for y in range(90, H) if (g[y, 20:W - 20] < 0xE8).mean() > 0.6]
    # rows: [tab-strip top, panel top, panel bottom, window bottom...]
    if len(rows) < 3:
        raise SystemExit("panel frame not found")
    top, bottom = rows[1] + 1, rows[2]
    return 3, top, W - 3, bottom


def wlit(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '\\"':
            out.append("\\" + ch)
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\u%04X" % o)
    return 'L"' + "".join(out) + '"'


def slug(stem):
    return stem.lower().replace(" ", "_")


def governs_for(cb, controls):
    """Controls on the same row to the right of a Default box, up to the next one."""
    cy = cb["y"] + cb["h"] / 2.0
    same = [c for c in controls if abs((c["y"] + c["h"] / 2.0) - cy) <= 7 and c["x"] > cb["x"]]
    nxt = min([c["x"] for c in same if c["control"] == "defaultcheck"] + [cb["x"] + 330])
    gov = [c["param"] for c in sorted(same, key=lambda c: c["x"])
           if c["control"] != "defaultcheck" and c["x"] < nxt]
    if not gov:
        base = cb["param"][:-len("Default")] if cb["param"].endswith("Default") else ""
        if base and any(c["param"] == base for c in controls):
            gov = [base]
    return gov


def main(shots, repo):
    tabs = []
    new_specs = {}
    for stem in ORDER:
        m = json.load(open(os.path.join(HERE, "maps", "map_%s.json" % stem)))
        img = Image.open(os.path.join(shots, stem + ".png")).convert("RGB")
        x0, y0, x1, y1 = panel_bounds(img)
        crop = img.crop((x0, y0, x1, y1))
        rel = "tekla146/tabs/%s.png" % slug(stem)
        os.makedirs(os.path.join(repo, "resources", "tekla146", "tabs"), exist_ok=True)
        crop.save(os.path.join(repo, "resources", rel), optimize=True)

        inside = [c for c in m["controls"]
                  if c["y"] >= y0 and c["y"] + c["h"] <= y1 and c["x"] >= x0 and c["x"] + c["w"] <= x1]
        # material/profile catalog squares are "..." buttons, not parameters
        inside = [c for c in inside if not (c["control"] == "check" and "Catalog" in c["param"])]
        ctls = []
        for c in inside:
            gov = governs_for(c, inside) if c["control"] == "defaultcheck" else []
            ctls.append(dict(param=c["param"], kind=KIND[c["control"]], x=c["x"] - x0,
                             y=c["y"] - y0, w=c["w"], h=c["h"], greyed=bool(c["greyed"]),
                             governs=gov))
            if c["control"] != "defaultcheck":
                if c["control"] == "check":
                    t, d = "B", c.get("value", "").strip().lower() == "checked"
                elif c["control"] in ("combo", "iconcombo"):
                    v = c.get("value", "").strip()
                    t, d = "E", (v if c["control"] == "combo" and v else "Default")
                else:
                    t, d = "S", c.get("value", "").strip()
                label = c.get("meaning", c["param"]).strip()
                label = label[:1].upper() + label[1:]
                new_specs.setdefault(c["param"], (t, d, label))
        tabs.append(dict(title=TITLES[stem], bg=":/" + rel.replace("tabs/", "tabs/"),
                         rel=rel, w=x1 - x0, h=y1 - y0, ctls=ctls))

    L = []
    L.append("// GENERATED by tools/tekla146_canvas/gen.py from the user's Tekla 146 tab")
    L.append("// screenshots + tools/tekla146_canvas/maps/*.json. Do not edit by hand.")
    L.append('#include "model_maker/component_dialog.hpp"')
    L.append("")
    L.append("#include <algorithm>")
    L.append("#include <set>")
    L.append("")
    L.append("namespace mm {")
    L.append("namespace {")
    L.append("struct Ctl {")
    L.append("    const wchar_t* param;")
    L.append("    PlacedControlKind kind;")
    L.append("    int x, y, w, h;")
    L.append("    bool greyed;")
    L.append("    const wchar_t* governs;  // '|' ayrimli")
    L.append("};")
    L.append("struct NewSpec {")
    L.append("    const wchar_t* name;")
    L.append("    char type;  // S string, E enum, B bool")
    L.append("    const wchar_t* def;")
    L.append("    const wchar_t* label;")
    L.append("};")
    L.append("")
    for i, t in enumerate(tabs):
        L.append("const Ctl kTab%d[] = {  // %s" % (i, t["title"]))
        for c in t["ctls"]:
            L.append("    {%s, PlacedControlKind::%s, %d, %d, %d, %d, %s, %s}," % (
                wlit(c["param"]), c["kind"], c["x"], c["y"], c["w"], c["h"],
                "true" if c["greyed"] else "false", wlit("|".join(c["governs"]))))
        L.append("};")
    L.append("")
    L.append("const NewSpec kSpecs[] = {")
    for name, (t, d, label) in new_specs.items():
        dv = ("1" if d else "0") if t == "B" else d
        L.append("    {%s, '%s', %s, %s}," % (wlit(name), t, wlit(dv), wlit(label)))
    L.append("};")
    L.append("")
    L.append("struct TabDef {")
    L.append("    const wchar_t* title;")
    L.append("    const wchar_t* background;")
    L.append("    int w, h;")
    L.append("    const Ctl* ctls;")
    L.append("    std::size_t n;")
    L.append("};")
    L.append("const TabDef kTabs[] = {")
    for i, t in enumerate(tabs):
        L.append("    {%s, %s, %d, %d, kTab%d, sizeof(kTab%d) / sizeof(Ctl)}," % (
            wlit(t["title"]), wlit(":/tekla146/" + t["rel"].split("tekla146/")[1]),
            t["w"], t["h"], i, i))
    L.append("};")
    L.append("")
    L.append("std::vector<std::wstring> splitBar(const wchar_t* s) {")
    L.append("    std::vector<std::wstring> out;")
    L.append("    std::wstring cur;")
    L.append("    for (const wchar_t* p = s; *p; ++p) {")
    L.append("        if (*p == L'|') { if (!cur.empty()) out.push_back(cur); cur.clear(); }")
    L.append("        else cur.push_back(*p);")
    L.append("    }")
    L.append("    if (!cur.empty()) out.push_back(cur);")
    L.append("    return out;")
    L.append("}")
    L.append("}  // namespace")
    L.append("")
    L.append("void applyShearPlate146Canvas(ComponentDialogDefinition& def) noexcept {")
    L.append("    const auto has = [&](const std::wstring& n) {")
    L.append("        return std::any_of(def.specs.begin(), def.specs.end(),")
    L.append("                           [&](const CompParamSpec& s) { return s.name == n; });")
    L.append("    };")
    L.append("    // 1) Ekran goruntusunde olup semada olmayan Tekla alanlari: GRI (documentedOnly).")
    L.append("    for (const auto& ns : kSpecs) {")
    L.append("        if (has(ns.name)) continue;")
    L.append("        CompParamSpec s;")
    L.append("        s.name = ns.name;")
    L.append("        s.description = ns.label;")
    L.append("        if (ns.type == 'B') {")
    L.append("            s.type = CompParamType::Boolean;")
    L.append("            s.defBool = ns.def[0] == L'1';")
    L.append("        } else if (ns.type == 'E') {")
    L.append("            s.type = CompParamType::Enum;")
    L.append("            s.defString = ns.def;")
    L.append("            s.choices = {ns.def};")
    L.append("        } else {")
    L.append("            s.type = CompParamType::String;")
    L.append("            s.defString = ns.def;")
    L.append("        }")
    L.append("        s.documentedOnly = true;")
    L.append("        def.specs.push_back(s);")
    L.append("    }")
    L.append("    // 2) Sekmeler: Tekla goruntusu arka plan + ayni piksel konumunda kontroller.")
    L.append("    std::set<std::wstring> placedNames;")
    L.append("    for (const auto& t : kTabs) {")
    L.append("        for (auto& g : def.schema.groups) {")
    L.append("            if (g.title != t.title) continue;")
    L.append("            g.layout = L\"canvas\";")
    L.append("            g.background = t.background;")
    L.append("            g.canvasWidth = t.w;")
    L.append("            g.canvasHeight = t.h;")
    L.append("            g.partRows.clear();")
    L.append("            g.figures.clear();  // Tekla resmi zaten sekmenin kendisi")
    L.append("            g.paramNames.clear();")
    L.append("            g.placed.clear();")
    L.append("            for (std::size_t i = 0; i < t.n; ++i) {")
    L.append("                const Ctl& c = t.ctls[i];")
    L.append("                DialogPlacedControl pc;")
    L.append("                pc.param = c.param;")
    L.append("                pc.kind = c.kind;")
    L.append("                pc.x = c.x; pc.y = c.y; pc.w = c.w; pc.h = c.h;")
    L.append("                pc.greyed = c.greyed;")
    L.append("                pc.governs = splitBar(c.governs);")
    L.append("                if (c.kind != PlacedControlKind::DefaultCheck) {")
    L.append("                    g.paramNames.push_back(pc.param);")
    L.append("                    placedNames.insert(pc.param);")
    L.append("                }")
    L.append("                g.placed.push_back(std::move(pc));")
    L.append("            }")
    L.append("        }")
    L.append("    }")
    L.append("    // 3) Hicbir sekmede yeri olmayan eski GRI alanlar kaldirilir (motor okumaz).")
    L.append("    def.specs.erase(std::remove_if(def.specs.begin(), def.specs.end(),")
    L.append("                                   [&](const CompParamSpec& s) {")
    L.append("                                       return s.documentedOnly && !placedNames.count(s.name);")
    L.append("                                   }),")
    L.append("                    def.specs.end());")
    L.append("}")
    L.append("")
    L.append("}  // namespace mm")
    with open(os.path.join(repo, "src", "component_dialog_146_canvas.cpp"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    for t in tabs:
        print("%-12s %3dx%3d %3d controls  %s" % (t["title"], t["w"], t["h"], len(t["ctls"]), t["rel"]))
    print("new/known specs:", len(new_specs))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.dirname(HERE)))
